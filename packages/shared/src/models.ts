export const modelKinds = ['image', 'llm', 'tts', 'video'] as const;
export type ModelKind = (typeof modelKinds)[number];
export interface ModelOption {
  key: string;
  label: string;
  type: 'select' | 'number' | 'boolean';
  choices?: readonly string[];
  min?: number;
  max?: number;
  integer?: boolean;
  default: string | number | boolean;
}
export interface ModelCapabilities {
  requiresStartImage?: boolean;
  imageToVideoRatio?: 'adaptive';
  maxPromptChars?: number;
  supportsDraft?: boolean;
  executionExpiresAfter?: number;
  rejectsRealPeople?: boolean;
  endImageRequiresStart?: boolean;
  maxImageMb?: number;
  maxInputChars?: number;
  supportsSpeed?: boolean;
  speedValues?: readonly number[];
  audio?: 'toggle' | 'included' | 'none';
  imageFormats?: readonly string[];
  minImagePixels?: number;
  maxImagePixels?: number;
  imageAspectRatio?: { min: number; max: number };
  maxRequestMb?: number;
  supportedParameters?: readonly string[];
  speechFormat?: 'mp3' | 'pcm';
  speechProvider?: 'elevenlabs' | 'google-ai-studio' | 'google-vertex';
  maxOutputTokens?: number;
  maxInputTokens?: number;
  contextLength?: number;

  aspectRatios?: readonly string[];
  resolutions?: readonly string[];
  durations?: readonly number[];
  maxCount?: number;
  maxReferences?: number;
  supportsEndImage?: boolean;
  supportsAudio?: boolean;
  supportsImageInput?: boolean;
  voices?: readonly string[];
  languages?: readonly string[];
  speed?: { min: number; max: number; default: number };
}
export interface ModelDefinition {
  id: string;
  kind: ModelKind;
  provider: string;
  providerModelId: string;
  label: string;
  status: 'active' | 'preview' | 'deprecated' | 'removed';
  aliases?: readonly string[];
  capabilities: ModelCapabilities;
  options: readonly ModelOption[];
  costUnits: number;
  pricing?: {
    source: string;
    checkedAt: string;
    inputUnit?: 'token' | 'character';
    promptUsd?: number;
    completionUsd?: number;
    rates?: readonly {
      billable: string;
      unit: string;
      costUsd: number;
      variant?: string;
    }[];
  };
}
export interface AvailableModel extends ModelDefinition {
  available: boolean;
  unavailableReason?: string;
  isDefault: boolean;
}
